#!/usr/bin/env python3
"""Generate an MIT-licensed freestanding project; never execute tools or fetch files."""
import argparse
import hashlib
import json
from pathlib import Path


RECIPE = (Path(__file__).resolve().parent.parent if "__file__" in globals() else Path.cwd()) / "recipes/bare-metal/arm-virt-a55.json"


def validate(recipe):
    # This is one supported behavioral contract, not an arbitrary SoC compiler.
    fixed = {
        "schemaVersion": 1, "id": "arm-virt-a55-hello-v1",
        "boardId": "arm-virt-a55", "machine": "virt-11.1",
        "cpu": "cortex-a55", "qemuVersion": [11, 1, 2],
        "ramBase": "0x40000000", "ramSize": "0x08000000",
        "entryOffset": "0x00200000", "stackSize": "0x00010000",
        "exceptionLevel": 1,
        "uart": {"model": "pl011", "base": "0x09000000", "clockHz": 24000000, "baud": 115200},
    }
    for key, value in fixed.items():
        if recipe.get(key) != value:
            raise ValueError(f"Unsupported recipe field: {key}")
    message = recipe.get("message")
    if not isinstance(message, str) or not 1 <= len(message) <= 120 or any(not 32 <= ord(c) <= 126 for c in message):
        raise ValueError("message must contain 1–120 printable ASCII characters")


def generate(recipe, output):
    validate(recipe)
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    # Protect generated sources, manifests and binaries even when users choose
    # an output directory outside the repository's ignored build/ directory.
    (output / ".gitignore").write_bytes(b"*\n")
    ram = int(recipe["ramBase"], 16)
    size = int(recipe["ramSize"], 16)
    entry = ram + int(recipe["entryOffset"], 16)
    stack = int(recipe["stackSize"], 16)
    uart = int(recipe["uart"]["base"], 16)
    # PL011 baud divisors: UARTCLK/(16*baud), fractional part in units of 1/64.
    divisor = (recipe["uart"]["clockHz"] * 4 + recipe["uart"]["baud"] // 2) // recipe["uart"]["baud"]
    message = json.dumps(recipe["message"] + "\r\n")
    license_line = "// SPDX-License-Identifier: MIT\n// Generated by Eidolon; regeneration creates fresh sources.\n"
    sources = {
        "startup.S": license_line + '''.section .text.boot, "ax"
.global _start
.type _start, %function
_start:
    msr daifset, #0xf
    msr spsel, #1
    ldr x0, =__stack_top
    mov sp, x0
    ldr x0, =__bss_start
    ldr x1, =__bss_end
1:  cmp x0, x1
    b.hs 2f
    str xzr, [x0], #8
    b 1b
2:  bl main
3:  wfi
    b 3b
''',
        "main.c": license_line + f'''#define UART_BASE 0x{uart:08x}UL
#define REG(offset) (*(volatile unsigned int *)(UART_BASE + (offset)))

static void uart_init(void) {{
    REG(0x30) = 0;                 // CR: disable before configuration.
    REG(0x44) = 0x7ff;             // ICR: clear interrupt status.
    REG(0x38) = 0;                 // IMSC: polling only.
    REG(0x24) = {divisor // 64};    // IBRD, UARTCLK = 24 MHz.
    REG(0x28) = {divisor % 64};     // FBRD.
    REG(0x2c) = 0x70;              // LCR_H: 8 data bits, FIFO, no parity.
    REG(0x30) = 0x101;             // CR: UARTEN | TXE.
}}

static void putc_uart(char value) {{
    while (REG(0x18) & (1u << 5)) {{ }} // FR: wait while TX FIFO is full.
    REG(0x00) = (unsigned char)value;
}}

static void puts_uart(const char *text) {{
    while (*text) putc_uart(*text++);
}}

void main(void) {{
    unsigned long level;
    __asm__ volatile ("mrs %0, CurrentEL" : "=r" (level));
    uart_init();
    puts_uart({message});
    puts_uart("Exception level: EL");
    putc_uart('0' + ((level >> 2) & 3));
    puts_uart("\\r\\n");
}}
''',
        "linker.ld": "/* SPDX-License-Identifier: MIT; generated by Eidolon. */\n" + f'''ENTRY(_start)
MEMORY {{ ram (rwx) : ORIGIN = 0x{entry:x}, LENGTH = 0x{ram + size - entry:x} }}
SECTIONS {{
    .text : {{ KEEP(*(.text.boot)) *(.text*) }} > ram
    .rodata : {{ *(.rodata*) }} > ram
    .data : {{ *(.data*) }} > ram
    .bss (NOLOAD) : {{
        . = ALIGN(8);
        __bss_start = .;
        *(.bss*) *(COMMON)
        . = ALIGN(8);
        __bss_end = .;
    }} > ram
    .stack (NOLOAD) : {{
        . = ALIGN(16);
        . += 0x{stack:x};
        __stack_top = .;
    }} > ram
    /DISCARD/ : {{ *(.comment) *(.note*) *(.eh_frame*) }}
}}
ASSERT(__stack_top <= ORIGIN(ram) + LENGTH(ram), "Firmware exceeds RAM")
''',
    }
    for name, contents in sources.items():
        (output / name).write_bytes(contents.encode("utf-8"))
    flags = ["--target=aarch64-none-elf", "-mcpu=cortex-a55", "-mgeneral-regs-only", "-ffreestanding", "-fno-builtin", "-fno-stack-protector", "-fno-pic", "-fno-pie", "-fno-unwind-tables", "-fno-asynchronous-unwind-tables", "-O2", "-Wall", "-Wextra", "-Werror"]
    plan = {
        "recipe": recipe,
        "sourcesSha256": {name: hashlib.sha256(contents.encode("utf-8")).hexdigest() for name, contents in sources.items()},
        "compileCommands": [flags + ["-c", name, "-o", name + ".o"] for name in ["startup.S", "main.c"]],
        "linkArgs": ["-T", "linker.ld", "--build-id=none", "startup.S.o", "main.c.o", "-o", "firmware.elf"],
        # Generic loader loads the ELF and sets PC to its entry without a Linux boot protocol.
        "qemuArgs": ["-machine", recipe["machine"] + ",secure=off,virtualization=off,gic-version=3", "-cpu", recipe["cpu"], "-accel", "tcg", "-smp", "1", "-m", "128M", "-display", "none", "-monitor", "none", "-nodefaults", "-no-user-config", "-nic", "none", "-serial", "file:serial.log", "-qmp", "stdio", "-S", "-device", "loader,file=firmware.elf,cpu-num=0"],
        "expectedSerial": recipe["message"] + "\r\nException level: EL1\r\n",
    }
    (output / "plan.json").write_bytes((json.dumps(plan, indent=2, sort_keys=True) + "\n").encode("utf-8"))
    return plan


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--recipe", type=Path, default=RECIPE)
    parser.add_argument("--recipe-json", help="Embedded recipe supplied by the desktop host")
    args = parser.parse_args()
    recipe = json.loads(args.recipe_json if args.recipe_json else args.recipe.read_text())
    generate(recipe, args.output)


if __name__ == "__main__":
    main()
